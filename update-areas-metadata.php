$update_stmt = $pdo->prepare("UPDATE service_areas SET zone = :zone, pincode = :pincode WHERE area_slug = :slug");

$all_areas = $pdo->query("SELECT id, area_name, area_slug, zone, pincode FROM service_areas")->fetchAll(PDO::FETCH_ASSOC);

$updated_count = 0;
$fallback_count = 0;

foreach ($all_areas as $area) {
    $slug = $area["area_slug"];
    
    // Direct match
    if (isset($area_data[$slug])) {
        $zone = $area_data[$slug][0];
        $pin  = $area_data[$slug][1];
    } else {
        // Partial match
        $matched = false;
        foreach ($area_data as $key => $val) {
            if (strpos($slug, $key) !== false || strpos($key, $slug) !== false) {
                $zone = $val[0];
                $pin  = $val[1];
                $matched = true;
                break;
            }
        }
        if (!$matched) {
            $zone = !empty($area["zone"]) && $area["zone"] != "Hyderabad" ? $area["zone"] : "Central Hyderabad";
            $pin  = !empty($area["pincode"]) ? $area["pincode"] : "500016";
            $fallback_count++;
        }
    }
    
    $update_stmt->execute([
        ":zone" => $zone,
        ":pincode" => $pin,
        ":slug" => $slug
    ]);
    $updated_count++;
}

echo "Successfully updated {$updated_count} service areas!\n";
